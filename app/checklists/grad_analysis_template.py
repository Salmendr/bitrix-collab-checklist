def template_items() -> list[dict]:
    """Every item of the file in the order of the file."""
    result = []
    for group in GROUPS:
        for order, (item_id, name, link_text, note, children) in enumerate(ITEMS[group["id"]], start=1):
            result.append({
                "id": item_id, "group": group["id"], "parentId": "", "order": order,
                "name": name, "linkText": link_text, "noteTemplate": note,
            })
            for child_order, (child_id, child_name, child_link, child_note) in enumerate(children, start=1):
                result.append({
                    "id": child_id, "group": group["id"], "parentId": item_id, "order": child_order,
                    "name": child_name, "linkText": child_link, "noteTemplate": child_note,
                })
    return result
